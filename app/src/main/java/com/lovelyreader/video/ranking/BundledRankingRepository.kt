package com.lovelyreader.video.ranking

import android.content.Context
import android.content.res.AssetManager
import android.util.Log
import java.io.BufferedReader
import java.io.InputStreamReader
import java.nio.charset.StandardCharsets
import java.security.MessageDigest
import java.time.Instant
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.json.JSONArray
import org.json.JSONObject

/**
 * Serves the signed-in-app, versioned public-source snapshot.
 *
 * This is intentionally a separate repository from [DefaultRankingRepository].
 * It gives a release a useful, deterministic first screen while a hosted
 * aggregator is unavailable, and keeps the exact same contract/validation
 * path as a future HTTPS service. The asset is regenerated by
 * `ranking-service/build_catalog.py`; it is not a debug fixture.
 */
class BundledRankingRepository(
    context: Context,
    private val nowMillis: () -> Long = System::currentTimeMillis
) : RankingRepository {
    private val appContext = context.applicationContext
    private val catalog by lazy {
        // Do not read the 40+ MB compatibility JSON into one String.  The
        // Android JSON object graph is several times larger than the source
        // text and made the complete catalogue fail on a normal 192 MB app
        // heap before the ranking screen could render.  The runtime index is
        // small; item rows are streamed from a gzipped JSON-lines asset only
        // for the current request.
        RankingCatalog(appContext.assets, appContext.assets.open(CATALOG_INDEX).bufferedReader(Charsets.UTF_8).use { it.readText() })
    }

    override suspend fun loadCapabilities(): Result<RankingCapabilities> = withContext(Dispatchers.IO) {
        runCatching { catalog.capabilities }
    }

    override suspend fun load(request: RankingRequest, forceRefresh: Boolean): RankingLoadResult = withContext(Dispatchers.IO) {
        val validation = validateRankingRequest(request)
        if (validation.isFailure) {
            return@withContext RankingLoadResult(
                snapshot = null,
                source = RankingDataSource.EMPTY,
                error = RankingError(RankingFailureKind.INVALID_REQUEST, "Invalid ranking request")
            )
        }
        runCatching {
            val snapshot = catalog.snapshot(request, nowMillis())
            RankingLoadResult(snapshot, RankingDataSource.BUNDLED)
        }.getOrElse {
            Log.e("BundledRanking", "catalog snapshot failed", it)
            RankingLoadResult(
                snapshot = null,
                source = RankingDataSource.EMPTY,
                error = RankingError(
                    kind = RankingFailureKind.MALFORMED_RESPONSE,
                    message = "Bundled ranking snapshot is invalid"
                )
            )
        }
    }
}

private class RankingCatalog(
    private val assets: AssetManager,
    indexJson: String
) {
    private val root = JSONObject(indexJson)
    private val catalogVersion = root.optString("catalogVersion", "unknown")
    private val methodologyVersion = root.optString("methodologyVersion").takeIf(String::isNotBlank)
    private val identityMapVersion = root.optString("identityMapVersion").takeIf(String::isNotBlank)
    private val catalogGeneratedAtMillis = root.optString("generatedAt")
        .takeIf(String::isNotBlank)
        ?.let { value -> runCatching { Instant.parse(value).toEpochMilli() }.getOrNull() }
    private val itemCount = root.optInt("itemCount", 0)
    private val itemAsset = root.optString("itemAsset", CATALOG_ITEMS_ASSET)
    private val sourceStatuses = root.optJSONArray("sourceStatuses") ?: JSONArray()
    private val coverage = root.optJSONObject("coverage") ?: error("missing catalog coverage")
    private val metadataCoverage = root.optJSONObject("metadataCoverage")
    /** Fingerprint the immutable asset so a cursor cannot cross catalogue revisions. */
    private val catalogFingerprint = root.optString("catalogFingerprint").takeIf { it.matches(Regex("[0-9a-f]{16}")) }
        ?: digest(root.toString())
    val capabilities: RankingCapabilities = parseRankingCapabilities(
        root.optJSONObject("capabilities")?.toString() ?: error("missing catalog capabilities")
    ).getOrThrow()

    fun snapshot(request: RankingRequest, now: Long): RankingSnapshot {
        require(request.boardId in capabilities.normalizedBoards().map { it.id }) { "unsupported board" }
        require(request.mediaType in capabilities.normalizedMediaTypes()) { "unsupported media type" }
        require(request.period == null || request.period in capabilities.normalizedPeriods().map { it.id }) { "unsupported period" }
        require(request.region == null || request.region in capabilities.normalizedRegions().map { it.id }) { "unsupported region" }
        require(request.year == null || request.year in capabilities.normalizedYears()) { "unsupported year" }
        require(request.genre == null || request.genre in capabilities.normalizedGenres().map { it.id }) { "unsupported genre" }

        val allEntries = collectMatchingRefs(request, now)
        val offset = bundledRankingOffset(request.cursor, catalogFingerprint)
        require(offset <= allEntries.size) { "cursor is outside bundled ranking snapshot" }
        val pageRefs = allEntries.drop(offset).take(request.limit)
        val nextOffset = (offset + pageRefs.size).takeIf { it < allEntries.size }

        val entries = readRows(pageRefs).mapIndexed { index, row ->
            val item = JSONObject(row)
            attachBundledPosterIfPresent(item)
                .put("rank", offset + index + 1)
                // Keep the exact confidence-weighted sort key beside the raw
                // source score so the UI can explain why two visible numbers
                // are intentionally different.
                .put("rankingScore", pageRefs[index].score)
        }

        val asOfMillis = minOf(
            catalogGeneratedAtMillis ?: (now.coerceAtLeast(1L) - 60_000L),
            now.coerceAtLeast(1L) - 60_000L
        )
        val generatedAt = Instant.ofEpochMilli(asOfMillis)
        val expiresAt = Instant.ofEpochMilli(now.coerceAtLeast(1L) + FRESH_MILLIS)
        val staleUntil = Instant.ofEpochMilli(now.coerceAtLeast(1L) + STALE_MILLIS)
        val snapshotJson = JSONObject()
            .put("schemaVersion", 1)
            .put("requestId", "bundled-${digest(request.toString())}")
            .put("boardId", request.boardId)
            .put("filters", filtersJson(request))
            // The cursor is a page position, not a new snapshot.  Keeping the
            // snapshot identity stable lets RankingViewModel merge every page
            // and prevents a valid page from being rejected as a different feed.
            .put("snapshotId", "${catalogVersion}-${catalogFingerprint}-${digest(request.copy(cursor = null).toString())}")
            .put("generatedAt", generatedAt.toString())
            .put("dataAsOf", generatedAt.toString())
            .put("expiresAt", expiresAt.toString())
            .put("staleUntil", staleUntil.toString())
            .put("freshness", "FRESH")
            .put("availability", if (entries.isEmpty()) "EMPTY" else "AVAILABLE")
            .put("coverage", JSONObject(coverage.toString()))
            .put("sourceStatuses", JSONArray(sourceStatuses.toString()))
            .put("items", JSONArray().also { array -> entries.forEach { array.put(it) } })
            .put("nextCursor", nextOffset?.let { bundledRankingCursor(it, catalogFingerprint) } ?: JSONObject.NULL)
            .put("totalCount", allEntries.size)

        metadataCoverage?.let { snapshotJson.put("metadataCoverage", JSONObject(it.toString())) }

        methodologyVersion?.let { snapshotJson.put("methodologyVersion", it) }
        identityMapVersion?.let { snapshotJson.put("identityMapVersion", it) }
        return parseRankingSnapshot(snapshotJson.toString(), now).getOrThrow()
    }

    private fun matches(item: JSONObject, request: RankingRequest, now: Long): Boolean {
        // A source board must never fall back to the aggregate score.  This
        // keeps an IMDb-only movie out of the TVmaze board and makes the
        // source tabs honest instead of being cosmetic labels.
        if (rankingBoardScore(item, request.boardId) == null) return false
        val mediaType = item.optString("mediaType")
        if (request.mediaType != RankingMediaType.ALL && mediaType != request.mediaType.name) return false
        if (request.region != null && !item.optJSONArray("countries").strings().contains(request.region)) return false
        val targetYear = rankingTargetYear(request.period, request.year, now)
        if (targetYear != null && item.optInt("releaseYear", -1) != targetYear) return false
        if (request.genre != null && !item.optJSONArray("genres").strings().contains(request.genre)) return false
        return true
    }

    /** A small sortable reference; the complete item JSON is never retained. */
    private data class ItemRef(
        val line: Int,
        val score: Double,
        val canonicalId: String,
        val genrePriority: Int
    )

    private fun collectMatchingRefs(request: RankingRequest, now: Long): List<ItemRef> {
        val refs = ArrayList<ItemRef>(itemCount.coerceAtMost(4096))
        openRows().useLines { lines ->
            lines.forEachIndexed { line, raw ->
                if (raw.isBlank()) return@forEachIndexed
                val item = JSONObject(raw)
                if (matches(item, request, now)) {
                    refs += ItemRef(
                        line,
                        rankingBoardSortScore(item, request.boardId) ?: 0.0,
                        item.optString("canonicalId"),
                        rankingPreferredGenrePriority(item.optJSONArray("genres").strings())
                    )
                }
            }
        }
        return refs.sortedWith(
            compareByDescending<ItemRef> { it.genrePriority }
                .thenByDescending { it.score }
                .thenBy { it.canonicalId }
        )
    }

    private fun readRows(refs: List<ItemRef>): List<String> {
        if (refs.isEmpty()) return emptyList()
        val wanted = refs.associateBy { it.line }
        val rows = HashMap<Int, String>(refs.size)
        openRows().useLines { lines ->
            lines.forEachIndexed { line, raw ->
                if (line in wanted) rows[line] = raw
            }
        }
        return refs.mapNotNull { rows[it.line] }
    }

    private fun attachBundledPosterIfPresent(item: JSONObject): JSONObject {
        if (!item.isNull("posterUrl")) return item
        val path = bundledPosterAssetPath(item.optString("canonicalId")) ?: return item
        return runCatching {
            assets.open(path).use { item.put("posterUrl", "asset://$path") }
            item
        }.getOrDefault(item)
    }

    private fun openRows(): BufferedReader = BufferedReader(
        // Android's asset packer transparently strips a source `.gz` suffix
        // and stores the bytes with normal ZIP deflate compression.  The
        // runtime therefore reads the resulting JSON-lines stream directly.
        InputStreamReader(openItemAsset(), Charsets.UTF_8),
        32 * 1024
    )

    private fun openItemAsset() = runCatching { assets.open(itemAsset) }
        .getOrElse { assets.open(itemAsset.removeSuffix(".gz")) }

    private fun filtersJson(request: RankingRequest): JSONObject = JSONObject()
        .put("period", request.period ?: JSONObject.NULL)
        .put("mediaType", request.mediaType.name)
        .put("region", request.region ?: JSONObject.NULL)
        .put("year", request.year ?: JSONObject.NULL)
        .put("genre", request.genre ?: JSONObject.NULL)
        .put("language", request.language ?: JSONObject.NULL)
        .put("limit", request.limit)
        .put("cursor", request.cursor ?: JSONObject.NULL)

    private fun JSONArray?.strings(): List<String> = if (this == null) emptyList() else {
        (0 until length()).mapNotNull { index -> optString(index).takeIf(String::isNotBlank) }
    }

    private fun digest(value: String): String = MessageDigest.getInstance("SHA-256")
        .digest(value.toByteArray(StandardCharsets.UTF_8))
        .joinToString("") { byte -> "%02x".format(byte.toInt() and 0xff) }
        .take(16)

    private companion object {
        const val FRESH_MILLIS = 24L * 60L * 60L * 1000L
        const val STALE_MILLIS = 72L * 60L * 60L * 1000L
    }
}

/**
 * Resolve the explicit year filter without inferring one from the period tab.
 * The UI's "全部" state is represented by a null [requestedYear]; it must
 * remain an all-years query even when the catalog period is annual.
 */
@Suppress("UNUSED_PARAMETER")
internal fun rankingTargetYear(period: String?, requestedYear: Int?, now: Long): Int? = requestedYear

/** Match the generator's deterministic asset name for a canonical identity. */
internal fun bundledPosterAssetPath(canonicalId: String): String? {
    if (canonicalId.isBlank()) return null
    val filename = buildString {
        canonicalId.forEach { char ->
            append(
                when {
                    char in 'a'..'z' || char in 'A'..'Z' || char in '0'..'9' || char == '.' || char == '_' || char == '-' -> char
                    else -> '_'
                }
            )
        }
        append(".img")
    }
    return "ranking/posters/$filename"
}

/** Opaque, deterministic page cursor used by the offline bundled snapshot. */
internal fun bundledRankingCursor(offset: Int, catalogFingerprint: String): String {
    require(offset >= 0) { "offset must be non-negative" }
    require(catalogFingerprint.matches(Regex("[0-9a-f]{16}"))) { "invalid catalog fingerprint" }
    return "offset:$catalogFingerprint:$offset"
}

internal fun bundledRankingOffset(cursor: String?, catalogFingerprint: String): Int {
    if (cursor == null) return 0
    val parts = cursor.split(':', limit = 3)
    require(parts.size == 3 && parts[0] == "offset" && parts[1] == catalogFingerprint && parts[2].isNotBlank() && parts[2].all(Char::isDigit)) {
        "invalid bundled ranking cursor"
    }
    return parts[2].toIntOrNull() ?: error("bundled ranking cursor is too large")
}

private const val CATALOG_INDEX = "ranking/catalog-index.json"
private const val CATALOG_ITEMS_ASSET = "ranking/items.ndjson.gz"

/**
 * Resolve a bundled row's score for one declared board.  Source boards are
 * deliberately strict: a missing source rating is not converted to zero and
 * is therefore excluded by [RankingCatalog.matches].
 */
internal fun rankingBoardScore(item: JSONObject, boardId: String): Double? {
    if (boardId == "aggregate") {
        return if (item.isNull("aggregateScore")) null else item.optDouble("aggregateScore").takeUnless(Double::isNaN)
    }
    if (!boardId.startsWith("source-")) return null
    val sourceId = boardId.removePrefix("source-")
    val ratings = item.optJSONArray("sourceRatings") ?: return null
    for (index in 0 until ratings.length()) {
        val rating = ratings.optJSONObject(index) ?: continue
        if (rating.optString("sourceId") != sourceId || rating.isNull("value")) continue
        return rating.optDouble("value").takeUnless(Double::isNaN)
    }
    return null
}

/**
 * Sort by Bayesian confidence when vote counts are available. Votes are only
 * used to move a low-sample score toward the catalog prior; they never amplify
 * a rating above its ten-point scale. The raw score remains the visible metric
 * and this value only controls rank order and pagination.
 */
internal const val RANKING_PRIOR_MEAN = 7.0
internal const val RANKING_PRIOR_VOTES = 1_000.0

/**
 * User-facing default ranking preference: put the most requested discovery
 * genres ahead of other genres, then keep the Bayesian score ordering inside
 * each group. An item is preferred when any of its (possibly multi-genre)
 * labels matches the set.
 */
internal fun rankingPreferredGenrePriority(genres: List<String>): Int =
    if (genres.any { it.trim() in PREFERRED_RANKING_GENRES }) 1 else 0

private val PREFERRED_RANKING_GENRES = setOf("喜剧", "动作", "恐怖", "悬疑", "惊悚")

internal fun rankingBayesianScore(
    score: Double,
    votes: Int,
    priorMean: Double = RANKING_PRIOR_MEAN,
    priorVotes: Double = RANKING_PRIOR_VOTES
): Double {
    if (!score.isFinite() || votes <= 0 || !priorVotes.isFinite() || priorVotes <= 0.0) return score
    val confidence = votes.toDouble() / (votes.toDouble() + priorVotes)
    return (score * confidence + priorMean * (1.0 - confidence)).coerceIn(0.0, 10.0)
}

internal fun rankingBoardSortScore(item: JSONObject, boardId: String): Double? {
    val score = rankingBoardScore(item, boardId) ?: return null
    val ratings = item.optJSONArray("sourceRatings") ?: return score
    val sourceId = boardId.removePrefix("source-")
    var votes = 0
    for (index in 0 until ratings.length()) {
        val rating = ratings.optJSONObject(index) ?: continue
        if (boardId != "aggregate" && rating.optString("sourceId") != sourceId) continue
        if (!rating.isNull("voteCount")) votes = maxOf(votes, rating.optInt("voteCount", 0))
    }
    return rankingBayesianScore(score, votes)
}
